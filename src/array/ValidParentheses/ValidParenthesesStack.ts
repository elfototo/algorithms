// Если стек пуст или скобки не совпадают, возвращаю false.

// Если скобки совпадают, удаляю последнюю открывающую скобку из стека.

// В конце проверяю, пуст ли стек. Если он пуст, все скобки закрыты правильно, поэтому возвращаю true. В противном случае возвращаю false.

// I would use a stack to solve this problem.

// A stack follows the Last In, First Out principle. This means that the last element we add is the first element we remove.

// First, I iterate through the string from left to right.

// If I find an opening bracket, I push it onto the stack.

// If I find a closing bracket, I check whether the stack is empty and whether the top element matches the closing bracket.

// If the stack is empty or the brackets don’t match, I return false.

// Otherwise, I pop the opening bracket from the stack.

// Finally, I check whether the stack is empty. If it is empty, the brackets are valid, so I return true. Otherwise, I return false.

// 4. Сложность алгоритма

// На собеседовании могут спросить об этом отдельно.

// Time complexity — O(n)

// We iterate through the string once, so the time complexity is O(n).

// Мы проходим по строке один раз. Если длина строки увеличивается вдвое, количество операций тоже растёт примерно вдвое.

// Space complexity — O(n)

// In the worst case, the stack can contain all the opening brackets, so the space complexity is O(n).

// В худшем случае строка состоит только из открывающих скобок, и все они окажутся в стеке.

// Здесь n — длина строки.






