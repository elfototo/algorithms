const a = "{[()]}";
const b = "{}[]()";
const c = "{]";

function isValid(s: string): boolean {
  const obg: Record<string, string> = {
    ")": "(",
    "]": "[",
    "}": "{",
  };

  const stack: string[] = [];

  for (let char of s) {
    if (char === "(" || char === "[" || char === "{") {
      stack.push(char);
    } else {
      if (stack.length === 0 || obg[char] !== stack[stack.length - 1]) {
        return false;
      }

      stack.pop();
    }
  }

  return stack.length === 0;
}

